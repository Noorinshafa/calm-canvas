// Google Analytics start-up code.
// It lives in its own file (instead of inline in index.html) because the
// site's Content-Security-Policy in vercel.json only allows scripts from
// 'self' and googletagmanager.com. Inline scripts are blocked by the browser.
window.dataLayer = window.dataLayer || [];
function gtag() {
  window.dataLayer.push(arguments);
}
gtag("js", new Date());
gtag("config", "G-X5KENE4P4D");
